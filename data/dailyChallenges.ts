/**
 * Returns today's challenge deterministically based on the current date.
 */
export function getChallengeForDate(date: Date = new Date()): DailyChallenge {
  const dayOfMonth = date.getDate(); // 1 to 31
  const match = DAILY_CHALLENGES.find((c) => c.dayNumber === dayOfMonth);
  return match || DAILY_CHALLENGES[0];
}
